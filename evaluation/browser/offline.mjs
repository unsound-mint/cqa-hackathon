import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const browser = await chromium.launch({executablePath:process.env.CQA_BROWSER_EXECUTABLE || '/usr/bin/chromium-browser',headless:true,args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[]; page.on('pageerror', e => errors.push(e.message));
const url=pathToFileURL(process.argv[2]).href;
await page.goto(url);
await page.locator('.card').first().waitFor();
assert.equal(await page.evaluate(()=>Boolean(window.PWNED)),false);
assert.equal(await page.locator('#msgs img, #msgs script').count(),0);
assert.equal(await page.locator('#reviewer').inputValue(),'Эльдана');
await page.locator('.card').first().getByRole('button',{name:'Да',exact:true}).click();
await page.locator('.msg').first().click();
const note=page.locator('.card').first().locator('textarea');
await note.fill('Fictional QA rationale');
await page.waitForTimeout(800);
assert.equal(await note.evaluate(el=>document.activeElement===el),true);
await page.reload();
await page.locator('.card').first().waitFor();
assert.equal(await page.locator('.card').first().getByRole('button',{name:'Да',exact:true}).getAttribute('aria-pressed'),'true');
assert.equal(await page.locator('.card').first().locator('textarea').inputValue(),'Fictional QA rationale');
assert.equal(await page.locator('.card').first().getByRole('button',{name:'Показать сообщение 0',exact:true}).count(),1);
assert.equal(await page.locator('#btnReport').count(),0);
const [download] = await Promise.all([page.waitForEvent('download'),page.locator('#btnBackup').click()]);
await download.saveAs('/tmp/cqa-fictional-backup.json');
const [csv] = await Promise.all([page.waitForEvent('download'),page.locator('#btnCsv').click()]);
await csv.saveAs('/tmp/cqa-fictional-export.csv');
await page.screenshot({path:'/tmp/cqa-label-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'/tmp/cqa-label-mobile.png',fullPage:true});
await page.evaluate(()=>localStorage.clear());
await page.reload();
await page.locator('#restore').setInputFiles('/tmp/cqa-fictional-backup.json');
await page.waitForLoadState();
await page.waitForTimeout(300);
assert.equal(await page.locator('.card').first().locator('textarea').inputValue(),'Fictional QA rationale');
assert.deepEqual(errors,[]);
// A second person starts blank; the first person's work and history remain intact.
const firstProfile = await page.locator('#profile').inputValue();
page.once('dialog', d => d.accept('Fictional second reviewer'));
await page.locator('#newProfile').click();
await page.waitForTimeout(300);
assert.equal(await page.locator('.card').first().getByRole('button',{name:'Да',exact:true}).getAttribute('aria-pressed'),'false');
assert.equal(await page.locator('.card').first().locator('textarea').inputValue(),'');
await page.locator('.card').first().getByRole('button',{name:'Нет',exact:true}).click();
await page.locator('#profile').selectOption(firstProfile);
await page.waitForTimeout(300);
assert.equal(await page.locator('.card').first().getByRole('button',{name:'Да',exact:true}).getAttribute('aria-pressed'),'true');
assert.equal(await page.locator('.card').first().locator('textarea').inputValue(),'Fictional QA rationale');
await browser.close();
console.log('Offline browser checks passed: answer, evidence, typing focus, persistence, backup/restore, CSV, narrow layout.');
